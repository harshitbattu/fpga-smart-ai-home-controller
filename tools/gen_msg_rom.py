#!/usr/bin/env python3
"""
gen_msg_rom.py : generates rtl/msg_rom.vh, the character look-up table used by
telemetry_tx.v. Every UART message has a fixed layout, so each character
position is either a constant or one field of the captured status.

Run:  python3 tools/gen_msg_rom.py
"""
import os

L = lambda s: [('lit', c) for c in s]          # literal text
F = lambda e: [('fld', e)]                      # one character from a field expression
CRLF = [('lit', '\r'), ('lit', '\n')]

def txt_by(cond_list, width):
    """one fixed-width text field chosen by conditions: [(cond, text), ..., (None, default)]"""
    out = []
    for i in range(width):
        expr = None
        for cond, t in reversed(cond_list):
            c = t.ljust(width)[i]
            lit = f'"{c}"' if c != ' ' else '8\'h20'
            expr = lit if cond is None else f'({cond}) ? {lit} : {expr}'
        out += F(expr)
    return out

SEC_TXT = txt_by([("c_sec == SEC_EXIT", "EXIT"), ("c_sec == SEC_ARMED", "ARMED"),
                  ("c_sec == SEC_ENTRY", "ENTRY"), ("c_sec == SEC_ALARM", "ALARM"),
                  (None, "DISARMED")], 8)
MODE_TXT = txt_by([("c_manual", "MANUAL"), (None, "AUTO")], 6)
b = lambda e: F(f'({e}) ? "1" : "0"')

msgs = {}
msgs['K_READY']  = L("SMART HOME CONTROLLER READY") + CRLF
msgs['K_GAS']    = L("EVT GAS_LEAK VALVE_CLOSED") + CRLF
msgs['K_INTR']   = L("EVT INTRUSION") + CRLF
msgs['K_GASCLR'] = L("EVT GAS_CLEAR SEND_ACK") + CRLF
msgs['K_LOCK']   = L("EVT LOCKOUT") + CRLF
msgs['K_ENTRY']  = L("EVT ENTRY_DELAY") + CRLF
msgs['K_ARMED']  = L("EVT ARMED") + CRLF
msgs['K_DISARM'] = L("EVT DISARMED") + CRLF
msgs['K_ANOM']   = L("EVT ANOMALY H=") + F("asc(c_ev_t)") + F("asc(c_ev_o)") + CRLF
msgs['K_INACT']  = L("EVT INACTIVITY H=") + F("asc(c_ev_t)") + F("asc(c_ev_o)") + CRLF
msgs['K_FAULT']  = L("EVT SENSOR_FAULT") + CRLF
msgs['K_OK']     = L("OK") + CRLF
msgs['K_ERR']    = L("ERR") + CRLF
msgs['K_DENIED'] = L("DENIED") + CRLF
msgs['K_LOCKED'] = L("LOCKED") + CRLF
msgs['K_STATUS'] = (L("T=") + F('!c_tok ? 8\'h20 : c_tneg ? "-" : "+"')
                    + F('c_tok ? asc(c_tt) : "-"') + F('c_tok ? asc(c_to) : "-"') + L(".")
                    + F('c_tok ? asc(c_tf) : "-"')
                    + L("C TH=") + F("asc(c_th_t)") + F("asc(c_th_o)")
                    + L(" FAN=") + F("asc(c_du_h)") + F("asc(c_du_t)") + F("asc(c_du_o)")
                    + L("% LIGHT=") + b("c_light")
                    + L(" MODE=") + MODE_TXT
                    + L(" ECO=") + b("c_eco")
                    + L(" SEC=") + SEC_TXT
                    + L(" GAS=") + b("c_gas")
                    + L(" OCC=") + b("c_occ")
                    + L(" PRED=") + b("c_pred")
                    + L(" FAULT=") + b("c_fault")
                    + L(" TIME=") + F("asc(c_hh_t)") + F("asc(c_hh_o)") + L(":")
                    + F("asc(c_mm_t)") + F("asc(c_mm_o)")
                    + L(" DAY=") + F("asc(c_dy_h)") + F("asc(c_dy_t)") + F("asc(c_dy_o)")
                    + L(" AI=") + F('!c_ail ? "-" : c_aio ? "1" : "0"')
                    + L(" P=") + F('c_ail ? asc(c_ap_h) : "-"') + F('c_ail ? asc(c_ap_t) : "-"') + F('c_ail ? asc(c_ap_o) : "-"') + L("%")
                    + CRLF)
prof = L("PROFILE DAYS=") + F("asc(c_dy_h)") + F("asc(c_dy_t)") + F("asc(c_dy_o)")
prof_slot = {}                                  # character position -> hour slot
for j in range(24):
    prof += L(f" {j:02d}=")
    for d in ('ps_h', 'ps_t', 'ps_o'):
        prof_slot[len(prof)] = j
        prof += F(f"asc({d})")
prof += CRLF
msgs['K_PROFILE'] = prof

def wh(bcd):
    return ([('fld', f"asc({bcd}[{4*q+3}:{4*q}])") for q in range(12, 6, -1)] + L(".")
            + [('fld', f"asc({bcd}[{4*q+3}:{4*q}])") for q in range(6, 2, -1)])
msgs['K_AI'] = (L("AI OCC=") + b("c_xo") + L(" P=") + F("asc(c_xp_h)") + F("asc(c_xp_t)") + F("asc(c_xp_o)")
                + L("%") + CRLF)
msgs['K_ENERGY'] = L("ENERGY FAN=") + wh("fan_bcd") + L("Wh LIGHT=") + wh("light_bcd") + L("Wh") + CRLF

CTRL = ('\r', '\n')

def lit_v(c):
    if c == '\r': return "8'h0D"
    if c == '\n': return "8'h0A"
    if c == ' ':  return "8'h20"
    if c == '"':  return "8'h22"
    return f'"{c}"'

out = []
fields = {}                                   # field expression -> id (1..)
for chars in msgs.values():
    for t, v in chars:
        if t == 'fld' and v not in fields:
            fields[v] = len(fields) + 1
FW = max(1, (len(fields)).bit_length())
out.append("// ============================================================================")
out.append("// msg_rom.vh : AUTO-GENERATED by tools/gen_msg_rom.py -- do not edit by hand")
out.append("// Two-stage character generator for every UART message (in telemetry_tx.v):")
out.append("//   stage 1 (registered): {kind, idx} -> literal character OR field number")
out.append("//   stage 2             : field number -> character from captured status")
out.append("// ============================================================================")
out.append(f"localparam integer MSG_FW = {FW};")
out.append("reg [7:0]        rom_lit, rom_lit_r;")
out.append("reg [MSG_FW-1:0] rom_fld, rom_fld_r;")
out.append("always @(*) begin")
out.append("    rom_lit = 8'h20;")
out.append("    rom_fld = 0;")
out.append("    len     = 8'd0;")
out.append("    case (kind)")
for name, chars in msgs.items():
    preview = ''.join(('#' if t == 'fld' else ('' if c in CTRL else c)) for t, c in chars)
    out.append(f"    {name}: begin  // {preview}")
    out.append(f"        len = 8'd{len(chars)};")
    out.append("        case (idx)")
    for i, (t, v) in enumerate(chars):
        if t == 'lit':
            out.append(f"            8'd{i}: rom_lit = {lit_v(v)};")
        else:
            out.append(f"            8'd{i}: rom_fld = {FW}'d{fields[v]};")
    out.append("            default: ;")
    out.append("        endcase")
    out.append("    end")
out.append("    default: ;")
out.append("    endcase")
out.append("end")
out.append("")
out.append("// captured only in the 2nd PREP cycle: {kind, idx} -> rom_*_r is a 2-cycle path")
out.append("// (see set_multicycle_path in the XDC)")
out.append("always @(posedge clk) if (rom_ce) begin rom_lit_r <= rom_lit; rom_fld_r <= rom_fld; end")
out.append("")
out.append("// stage 2: field characters")
out.append("always @(*) begin")
out.append("    case (rom_fld_r)")
out.append("        0: ch = rom_lit_r;")
for e, k in fields.items():
    out.append(f"        {k}: ch = {e};")
out.append("        default: ch = 8'h20;")
out.append("    endcase")
out.append("end")
out.append("")
out.append("// profile slot (hour) whose score is printed at this character position")
out.append("always @(*) begin")
out.append("    pj = 5'd0;")
out.append("    if (kind == K_PROFILE)")
out.append("        case (idx)")
for pos, j in prof_slot.items():
    out.append(f"            8'd{pos}: pj = 5'd{j};")
out.append("            default: pj = 5'd0;")
out.append("        endcase")
out.append("end")

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, '..', 'rtl', 'msg_rom.vh')
open(path, 'w').write('\n'.join(out) + '\n')
for n, c in msgs.items():
    print(f"{n:10s} length {len(c)}")
