#!/usr/bin/env python3
"""
train_nn.py : trains the occupancy-detection neural network and exports it
for the FPGA.

Dataset : UCI "Occupancy Detection" (Candanedo & Feldheim, Energy and Buildings 2016)
          datatraining.txt (training), datatest.txt + datatest2.txt (unseen test)
Model   : MLP 4 -> 8 (ReLU) -> 1, inputs = temperature, humidity, light, CO2
Export  : 8-bit fixed-point weights (rtl/nn_weights.vh), sigmoid LUT, and test
          vectors with the bit-exact integer reference result (ai/*.hex)

The integer model in `int_infer` is EXACTLY what the Verilog nn_engine computes.
"""
import csv, json, math, os
import numpy as np
from sklearn.neural_network import MLPClassifier

HERE = os.path.dirname(os.path.abspath(__file__))
RTL = os.path.join(HERE, "..", "rtl")
np.random.seed(0)

def load(fn):
    X, y = [], []
    with open(os.path.join(HERE, fn)) as f:
        r = csv.reader(f); next(r)
        for row in r:
            T, RH, L, C = float(row[2]), float(row[3]), float(row[4]), float(row[5])
            # integer form sent to the FPGA: T and RH in 0.1 units, light in lux, CO2 in ppm
            X.append([round(T * 10), round(RH * 10), min(9999, round(L)), min(9999, round(C))])
            y.append(int(row[7]))
    return np.array(X, dtype=np.int64), np.array(y)

Xtr, ytr = load("datatraining.txt")
Xt1, yt1 = load("datatest.txt")
Xt2, yt2 = load("datatest2.txt")
Xte = np.vstack([Xt1, Xt2]); yte = np.concatenate([yt1, yt2])

# ---------------- input normalisation (done in hardware) ----------------
# xq = clamp(((x - MU) * K) >> 12, -127, 127), i.e. 1 standard deviation = 32 counts
mu = Xtr.mean(0); sd = Xtr.std(0)
MU = np.round(mu).astype(np.int64)
K = np.round(4096 * 32 / sd).astype(np.int64)

def norm_int(X):
    return np.clip(((X - MU) * K) >> 12, -127, 127)

Xtr_q = norm_int(Xtr); Xte_q = norm_int(Xte)

# ---------------- train (float) on the quantised inputs ----------------
clf = MLPClassifier(hidden_layer_sizes=(8,), activation="relu", solver="adam", alpha=1.0,
                    max_iter=3000, random_state=1)
clf.fit(Xtr_q / 32.0, ytr)
acc_float = (clf.predict(Xte_q / 32.0) == yte).mean()
W1, W2 = clf.coefs_[0].T, clf.coefs_[1][:, 0]          # W1: 8x4, W2: 8
b1, b2 = clf.intercepts_[0], clf.intercepts_[1][0]

# ---------------- quantise to 8-bit weights ----------------
a1 = 127 / np.abs(W1).max()
W1q = np.round(W1 * a1).astype(np.int64)
b1q = np.round(b1 * a1 * 32).astype(np.int64)
acc1_tr = np.maximum(Xtr_q @ W1q.T + b1q, 0)
g = 127 / (acc1_tr.max() / (a1 * 32))                     # hidden scale
M1 = int(round(g / (a1 * 32) * 65536))                   # requant multiplier (>>16)
a2 = 127 / np.abs(W2).max()
W2q = np.round(W2 * a2).astype(np.int64)
b2q = int(round(b2 * a2 * g))

def int_infer(Xq):
    acc1 = np.maximum(Xq @ W1q.T + b1q, 0)
    h = np.clip((acc1 * M1) >> 16, 0, 127)
    acc2 = h @ W2q + b2q
    return acc2

z_te = int_infer(Xte_q)
pred_int = (z_te > 0).astype(int)
acc_int = (pred_int == yte).mean()
z_tr = int_infer(Xtr_q)
acc_int_tr = ((z_tr > 0) == ytr).mean()

tp = int(((pred_int == 1) & (yte == 1)).sum()); tn = int(((pred_int == 0) & (yte == 0)).sum())
fp = int(((pred_int == 1) & (yte == 0)).sum()); fn = int(((pred_int == 0) & (yte == 1)).sum())

# ---------------- baselines for comparison ----------------
def best_threshold(feat):
    best = (0, 0)
    for t in np.unique(Xtr[:, feat]):
        a = ((Xtr[:, feat] >= t) == ytr).mean()
        if a > best[0]: best = (a, t)
    return best[1], ((Xte[:, feat] >= best[1]) == yte).mean()
thr_light, acc_light = best_threshold(2)
thr_co2, acc_co2 = best_threshold(3)
thr_temp, acc_temp = best_threshold(0)
from sklearn.linear_model import LogisticRegression
acc_lr = LogisticRegression(max_iter=3000).fit(Xtr_q/32.0, ytr).score(Xte_q/32.0, yte)

# ---------------- sigmoid LUT: index = clamp(acc2 >> SH, -128, 127) ----------------
SH = max(0, int(math.ceil(math.log2(max(1, np.abs(z_te).max() / 127.0)))))
def prob_pct(idx):
    zr = ((idx << SH) + (1 << SH) / 2) / (a2 * g) if SH > 0 else idx / (a2 * g)
    return int(round(100 / (1 + math.exp(-zr))))
lut = [prob_pct(i) for i in range(-128, 128)]

# ---------------- export Verilog include ----------------
def s8(v): return f"8'sd{v}" if v >= 0 else f"-8'sd{-v}"
lines = ["// ============================================================================",
         "// nn_weights.vh : AUTO-GENERATED by ai/train_nn.py -- do not edit by hand",
         "// Occupancy MLP 4-8-1 (ReLU), trained on the UCI Occupancy Detection dataset",
         f"// float test accuracy {acc_float*100:.2f} %, 8-bit hardware model {acc_int*100:.2f} %",
         "// ============================================================================",
         "// input normalisation: xq = clamp(((x - MU) * K) >> 12, -127, 127)"]
for i, n in enumerate(["TEMP_x10", "RH_x10", "LUX", "CO2"]):
    lines.append(f"localparam signed [15:0] NN_MU{i} = 16'sd{MU[i]};   // {n} mean")
    lines.append(f"localparam signed [15:0] NN_K{i}  = 16'sd{K[i]};   // 4096*32/std")
lines.append(f"localparam [17:0] NN_M1 = 18'd{M1};          // hidden requantisation (>>16)")
lines.append(f"localparam signed [23:0] NN_B2 = {'-' if b2q<0 else ''}24'sd{abs(b2q)};")
lines.append(f"localparam integer NN_SH = {SH};                 // sigmoid LUT index shift")
lines.append("function signed [7:0] nn_w1;  // W1[j][i]")
lines.append("    input [2:0] j; input [1:0] i;")
lines.append("    case ({j, i})")
for j in range(8):
    for i in range(4):
        lines.append(f"        5'd{j*4+i}: nn_w1 = {s8(W1q[j][i])};")
lines.append("        default: nn_w1 = 8'sd0;\n    endcase\nendfunction")
lines.append("function signed [23:0] nn_b1;  // b1[j]")
lines.append("    input [2:0] j;\n    case (j)")
for j in range(8):
    v = b1q[j]; lines.append(f"        3'd{j}: nn_b1 = {'-' if v<0 else ''}24'sd{abs(v)};")
lines.append("        default: nn_b1 = 24'sd0;\n    endcase\nendfunction")
lines.append("function signed [7:0] nn_w2;  // W2[j]")
lines.append("    input [2:0] j;\n    case (j)")
for j in range(8):
    lines.append(f"        3'd{j}: nn_w2 = {s8(W2q[j])};")
lines.append("        default: nn_w2 = 8'sd0;\n    endcase\nendfunction")
lines.append("function [6:0] nn_prob;        // sigmoid(z) in percent, index = clamp(acc2>>SH)")
lines.append("    input [7:0] idx;           // two's complement -128..127\n    case (idx)")
for k, i in enumerate(range(-128, 128)):
    lines.append(f"        8'd{i & 0xFF}: nn_prob = 7'd{lut[k]};")
lines.append("        default: nn_prob = 7'd50;\n    endcase\nendfunction")
open(os.path.join(RTL, "nn_weights.vh"), "w").write("\n".join(lines) + "\n")

# ---------------- test vectors (all unseen test rows) ----------------
with open(os.path.join(HERE, "nn_test_vectors.mem"), "w") as f:
    for x, y, z in zip(Xte, yte, z_te):
        f.write(f"{x[0]&0xFFFF:04x}{x[1]&0xFFFF:04x}{x[2]&0xFFFF:04x}{x[3]&0xFFFF:04x}{int(y):01x}{int(z)&0xFFFFFF:06x}\n")

res = {"n_train": int(len(ytr)), "n_test": int(len(yte)), "occupied_frac_test": float(yte.mean()),
       "acc_float": float(acc_float), "acc_int8": float(acc_int), "acc_int8_train": float(acc_int_tr),
       "tp": tp, "tn": tn, "fp": fp, "fn": fn,
       "precision": tp / (tp + fp), "recall": tp / (tp + fn),
       "baseline_light_thr": int(thr_light), "baseline_light_acc": float(acc_light),
       "baseline_co2_thr": int(thr_co2), "baseline_co2_acc": float(acc_co2),
       "baseline_temp_acc": float(acc_temp), "logreg_acc": float(acc_lr), "always_empty_acc": float(1 - yte.mean()),
       "MU": MU.tolist(), "K": K.tolist(), "M1": M1, "b2q": b2q, "SH": SH,
       "W1q": W1q.tolist(), "b1q": b1q.tolist(), "W2q": W2q.tolist(),
       "max_abs_acc2": int(np.abs(z_te).max())}
json.dump(res, open(os.path.join(HERE, "nn_results.json"), "w"), indent=1)
for k in ["n_train", "n_test", "occupied_frac_test", "acc_float", "acc_int8", "acc_int8_train", "tp", "tn", "fp", "fn",
          "precision", "recall", "baseline_light_acc", "baseline_co2_acc", "baseline_temp_acc", "logreg_acc", "always_empty_acc",
          "M1", "b2q", "SH", "max_abs_acc2"]:
    print(f"{k:22s} {res[k]}")
print("W1q", W1q.tolist()); print("b1q", b1q.tolist()); print("W2q", W2q.tolist())
